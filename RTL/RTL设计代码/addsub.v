//=============================================================================
// 文件名 : addsub.v
// 功能   : 加法/减法器, 位宽可以改, 纯组合逻辑。Karatsuba 中间量运算都用它。
//
// 为什么要做这个 :
//   Karatsuba 里 (x1+x0)(y1+y0) - x1y1 - x0y0 要减法,
//   顶层拼结果 p = w0 + (z1<<64) + (w2<<128) 要宽位加法。
//   所以做一个单元, 加减都管, 用 op 选:
//       op = 1'b0 -> s = x + y
//       op = 1'b1 -> s = x - y   (二进制补码, 借位不管)
//   顶层只放一个实例, 靠微码分时用, 省面积。
//
// 端口 :
//   op : 1'b0 加, 1'b1 减
//   x  : 被加数/被减数
//   y  : 加数/减数
//   s  : 结果, 和操作数一样宽
//
// 注意 : 减法结果当无符号补码看。Karatsuba 里 z1 可能是负的,
//        所以调用方给的寄存器要比被减数宽 1~2 位, 用来装借位,
//        后面再靠运算的符号含义保证结果对(位宽怎么推的见 karatsuba128.v)。
//
// 语言   : Verilog-2001。纯组合逻辑, 没用厂商原语。
//=============================================================================
`timescale 1ns/1ps

module addsub #(
    parameter integer WD = 128        // 操作数和结果的位宽
) (
    input  wire            op,        // 1'b0: x+y   1'b1: x-y
    input  wire [WD-1:0]   x,
    input  wire [WD-1:0]   y,
    output wire [WD-1:0]   s
);

    assign s = op ? (x - y) : (x + y);

endmodule
